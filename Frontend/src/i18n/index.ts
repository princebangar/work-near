const dicts: Record<Lang, Dict> = { en, hi };

/** Translator for the current language. Falls back to English when admin switches the Hindi feature off. */
export function useT() {
  const lang = usePrefs((s) => s.lang);
  const hindi = useFeature('hindi');
  const d = dicts[hindi ? lang : 'en'];
  return (k: TKey) => d[k] ?? en[k];
}
